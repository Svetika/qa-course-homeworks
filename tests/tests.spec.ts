import { test, expect } from '@playwright/test';

function getVotingMessage(age: number): string {
  if (age < 0) {
    throw new Error("Вік не може бути від'ємним числом.");
  } else if (Number.isInteger(age)) {
    if (age >= 18) {
      return "Ви можете голосувати.";
    } else {
      return "Ви ще не можете голосувати.";
    }
  } else {
    throw new Error("Вік має бути цілим числом.");
  }
};

//Класи еквівалентності:

//користувачі молодші за 18 років;
//користувачі віком від 18 років включно.
//Обов’язково перевірте три граничні значення:

//Вік	Що перевіряємо	Очікуваний результат
//17	Значення перед порогом	"Ви ще не можете голосувати."
//18	Сам поріг	"Ви можете голосувати."
//19	Значення після порога	"Ви можете голосувати."

test("вік більший або рівний 18 повертає 'Ви можете голосувати.'", () => {
  expect(getVotingMessage(18)).toBe("Ви можете голосувати.");
});

test("від’ємне число повертає 'Вік не може бути від'ємним числом.'", () => {
  expect(() => getVotingMessage(-1)).toThrow("Вік не може бути від'ємним числом.");
});

test("вік менше 18 років повертає 'Ви ще не можете голосувати.'", () => {
  expect(getVotingMessage(17)).toBe("Ви ще не можете голосувати.");
});

test("неціле число повертає 'Вік має бути цілим числом.'", () => {
  expect(() => getVotingMessage(18.5)).toThrow("Вік має бути цілим числом.");
});

